<h3>¿Qué es la Facturación?</h3>
<p>
    Este módulo permite emitir comprobantes a partir de pedidos ya <strong>PREPARADOS</strong>
    o como <strong>venta inmediata</strong> (sin pedido previo).
</p>

<h3>Flujo de facturación</h3>
<ol>
    <li><strong>Guardar factura</strong>: asigna número de remito, descuenta stock (artículos e insumos) y marca el pedido como FACTURADO. La factura queda <em>pendiente de ARCA</em>.</li>
    <li><strong>Enviar a ARCA</strong> (opcional, cuando quieras): obtiene el CAE y el número legal. Recién ahí se puede imprimir la factura.</li>
    <li><strong>Imprimir remito</strong> en cualquier momento: con precio (para el cliente) o sin precio (para el transportista).</li>
    <li><strong>Anular</strong>: revierte el stock y devuelve el pedido a PREPARADO si corresponde.</li>
</ol>

<div class="ayuda-tip">
    <strong>Doble emisor:</strong> al crear una factura podés elegir <strong>quién factura</strong>.
    Cada emisor tiene su propio certificado ARCA, punto de venta y contador de remitos.
</div>

<h3>Artículos sin cargo</h3>
<p>
    Las líneas marcadas <strong>Sin cargo</strong> se descuentan del stock y aparecen en el remito,
    pero <strong>NO se envían a ARCA</strong>. Útil para muestras o bonificaciones.
</p>

<h3>Venta inmediata</h3>
<p>
    Desde el botón <strong>Nueva factura</strong> podés cargar un cliente y sus artículos sin
    pasar por un pedido. Se usa cuando el cliente viene directo a buscar la mercadería.
</p>