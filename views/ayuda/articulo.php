<h3>¿Qué es un artículo?</h3>
<p>
    Un <strong>artículo</strong> es un producto terminado que vendés a tus clientes.
    Se compone de una <strong>fórmula</strong> de insumos (alcohol, esencias, envases, etiquetas, etc.)
    y tiene precios diferenciados por categoría de cliente.
</p>

<h3>Alta de un artículo</h3>
<ol>
    <li>Completá <strong>nombre</strong> y descripción. El código es opcional.</li>
    <li>Guardá. Se te redirige a la edición con todas las secciones disponibles.</li>
    <li>Cargá la <strong>fórmula</strong>: elegí insumos y cantidades (en la unidad del insumo).</li>
    <li>Subí una <strong>imagen</strong> (se recorta a 600×600).</li>
    <li>Ingresá los <strong>precios por categoría</strong> y definí la visibilidad en listas.</li>
</ol>

<div class="ayuda-tip">
    <strong>Tip:</strong> si el artículo tiene costo automático, el sistema recalcula el costo cada vez
    que cambia el costo de alguno de sus insumos. Si es manual, el costo lo definís vos.
</div>

<h3>Sobre la fórmula</h3>
<p>
    Cada línea de la fórmula dice <em>"cuántas unidades de stock del insumo se necesitan"</em>.
    Ejemplo: si el insumo está cargado como <code>Litro</code>, poner 0.75 significa 750 ml.
</p>

<div class="ayuda-warning">
    <strong>Importante:</strong> el recálculo es en cascada. Si cambiás el costo del alcohol,
    <strong>todos</strong> los artículos que lo usan se recalculan automáticamente.
</div>

<h3>Precios por categoría</h3>
<p>
    Hay 4 categorías (Distribuidor, Distribuidor Final, Local, Mayorista). Para cada una:
</p>
<ul>
    <li><strong>Precio</strong>: el valor final que se factura.</li>
    <li><strong>Visible en lista</strong>: si se incluye o no cuando generes la lista de precios.</li>
</ul>
<p>
    Un precio de <code>0</code> con visible destildado sirve para artículos sin cargo
    que se envían como cortesía y no se facturan.
</p>

<h3>Imagen</h3>
<p>
    Hacé click en <strong>Subir imagen</strong>. Se va a abrir un editor donde podés
    arrastrar, hacer zoom y elegir el recorte. El sistema guarda la imagen final a 600×600 px.
</p>