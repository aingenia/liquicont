<h3>¿Qué son las Estadísticas?</h3>
<p>
    Son informes visuales para entender cómo va el negocio: qué se vende, a quién,
    en qué formato y qué sabores tienen más salida. Todos los datos salen de las
    <strong>facturas emitidas</strong> (no de pedidos).
</p>

<h3>Filtros generales</h3>
<p>Arriba de todo hay un filtro común que afecta a todos los informes:</p>
<ul>
    <li><strong>Desde / Hasta</strong> — rango de fechas.</li>
    <li><strong>Año actual</strong> — atajo para el 1 de enero hasta hoy.</li>
    <li><strong>Últimos 30 días</strong> — atajo para el último mes.</li>
    <li><strong>Año anterior</strong> — atajo para el año calendario previo completo.</li>
</ul>

<h3>Los 5 informes</h3>

<h4>1. Facturación por emisor</h4>
<p>
    Muestra cuánto se facturó con cada razón social en el período. Barras
    comparativas con el total facturado por emisor.
</p>

<h4>2. Ventas mes vs mes (año a año)</h4>
<p>
    Compara las <strong>cajas equivalentes</strong> vendidas en cada mes, año contra año.
    Podés activar/desactivar años con los chips de colores.
</p>
<div class="ayuda-tip">
    <strong>¿Qué es una "caja equivalente"?</strong><br>
    144 botellas de 200cc equivalen a <strong>6 cajas de 24</strong>.<br>
    144 botellas de 750cc equivalen a <strong>24 cajas de 6</strong>.<br>
    Así se pueden comparar formatos distintos en la misma unidad.
</div>

<h4>3. Formatos</h4>
<p>
    Distribución de cajas por formato (200cc, 750cc...). Tenés 2 gráficos:
</p>
<ul>
    <li><strong>Barras horizontales</strong> — valores absolutos en cajas.</li>
    <li><strong>Donut con porcentajes</strong> — share de cada formato.</li>
</ul>

<h4>4. Cajas por cliente</h4>
<p>
    Ranking de los clientes que más cajas compran en el período. Podés cambiar
    el "Top" de 10 a 50 con el selector.
</p>

<h4>5. Share de sabores</h4>
<p>
    Distribución de unidades por sabor, con gráfico de torta + tabla detallada al costado.
    Podés filtrar por formato (200cc o 750cc) para ver el share dentro de cada uno.
</p>

<h3>Cómo se identifica el "formato" y "sabor"</h3>
<p>
    Se derivan del <strong>código</strong> del artículo:
</p>
<ul>
    <li><strong>Formato</strong> — los dígitos iniciales del código (ej: <code>200CC</code> → formato <code>200</code>).</li>
    <li><strong>Sabor</strong> — el resto del código (ej: <code>200CC</code> → sabor <code>CC</code>).</li>
</ul>
<p>
    Si algún artículo no cae correctamente, podés editarlo a mano desde
    <strong>Artículos → Editar</strong> (campos "Formato" y "Sabor").
</p>

