<h3>¿Qué es el módulo de Contabilidad?</h3>
<p>
    Es la contabilidad <strong>gerencial</strong> de LiquiCont: sirve para llevar el registro
    de las operaciones con <strong>partida doble</strong> (todo movimiento tiene un Debe
    y un Haber que balancean), y obtener reportes internos.
</p>
<div class="ayuda-tip">
    <strong>No reemplaza al contador.</strong> Es una herramienta de gestión. Tu contador
    sigue usando su sistema oficial para impuestos y presentaciones.
</div>

<h3>Conceptos básicos</h3>
<ul>
    <li><strong>Plan de cuentas</strong> — la lista de todas las cuentas contables. Es un árbol jerárquico: las cuentas <em>imputables</em> (último nivel) reciben asientos.</li>
    <li><strong>Asiento</strong> — cada movimiento contable. Tiene fecha, descripción, y 2 o más líneas (Debe / Haber).</li>
    <li><strong>Ejercicio contable</strong> — un período (por ej. un año). Se abre, se opera, y se cierra. Podés elegir la fecha de inicio.</li>
    <li><strong>Emisor</strong> — cada asiento pertenece a una razón social (Roky MdQ, Jorge, etc.).</li>
</ul>

<h3>Cómo se organiza el menú</h3>
<ul>
    <li><strong>Contabilidad</strong> — dashboard con accesos rápidos.</li>
    <li><strong>Ejercicios</strong> — alta, cierre y reapertura.</li>
    <li><strong>Plan de cuentas</strong> — el árbol de cuentas.</li>
    <li><strong>Asientos</strong> — listado y alta manual.</li>
    <li><strong>Libro Diario</strong> — todos los movimientos por fecha.</li>
    <li><strong>Libro Mayor</strong> — movimientos de una cuenta con saldo corriente.</li>
    <li><strong>Balance de Sumas y Saldos</strong> — resumen con saldos por cuenta.</li>
</ul>

<h3>Estados de un asiento</h3>
<ul>
    <li><strong>Borrador</strong> — se puede editar y eliminar. No impacta en reportes.</li>
    <li><strong>Confirmado</strong> — asentado. No se puede editar (solo anular). Impacta en reportes.</li>
    <li><strong>Anulado</strong> — queda registrado pero no se computa en reportes.</li>
</ul>
<div class="ayuda-tip">
    <strong>Regla de oro:</strong> el asiento no puede confirmarse si el total del Debe
    no coincide con el total del Haber. El sistema lo valida automáticamente.
</div>

<h3>Reglas del ejercicio contable</h3>
<ul>
    <li>Solo puede haber <strong>un ejercicio abierto</strong> a la vez.</li>
    <li>Los asientos deben tener fecha <strong>dentro del rango del ejercicio</strong>.</li>
    <li>Un ejercicio se puede <strong>cerrar</strong> solo si no tiene asientos en borrador.</li>
    <li>Un ejercicio sin asientos se puede <strong>eliminar</strong>.</li>
    <li>Un ejercicio cerrado se puede <strong>reabrir</strong> si fue un error.</li>
</ul>

<h3>Permisos</h3>
<p>Solo <strong>Administrador</strong> puede acceder a este módulo.</p>