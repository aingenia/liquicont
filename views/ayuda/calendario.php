<h3>¿Qué es el Calendario de Cheques?</h3>
<p>
    Es una agenda visual donde se registran los <strong>cheques que van a hacerse efectivos
    en una fecha determinada</strong>. Sirve para no perder de vista los vencimientos y
    saber cuánto dinero va a entrar o salir en cada día.
</p>

<h3>Cómo agregar un cheque</h3>
<ol>
    <li>Hacé clic sobre el <strong>día</strong> en el calendario.</li>
    <li>Se abre una ventana con los cheques que ya están cargados para esa fecha (si hay).</li>
    <li>Completá el formulario de abajo:
        <ul>
            <li><strong>Importe *</strong> — el monto del cheque.</li>
            <li><strong>Tipo</strong> — <em>Propio</em> (vos lo emitís) o <em>Tercero</em> (te lo entregó un cliente).</li>
            <li><strong>Banco</strong> — opcional, para identificar de qué banco es.</li>
            <li><strong>N° Cheque</strong> — opcional, el número del cheque.</li>
            <li><strong>Descripción</strong> — opcional, para aclaraciones (ej: "Pago proveedor X").</li>
        </ul>
    </li>
    <li>Presioná <strong>Agregar cheque</strong>.</li>
</ol>

<div class="ayuda-tip">
    <strong>Tip:</strong> podés cargar <strong>varios cheques para el mismo día</strong>.
    Se van a apilar uno debajo del otro y al final del modal vas a ver el
    <strong>total acumulado</strong> del día.
</div>

<h3>Cómo editar un cheque</h3>
<ol>
    <li>Hacé clic sobre el día que tenga cheques cargados.</li>
    <li>En la lista, buscá el cheque que querés modificar.</li>
    <li>Presioná el botón <strong>Editar</strong> (con el ícono del lápiz).</li>
    <li>El formulario de abajo se rellena automáticamente con los datos del cheque.</li>
    <li>Modificá lo que necesites y presioná <strong>Guardar cambios</strong>.</li>
</ol>

<p>
    Si cambiaste de opinión, presioná <strong>Cancelar</strong> para vaciar el formulario
    y volver al modo "Agregar cheque".
</p>

<h3>Cómo eliminar un cheque</h3>
<ol>
    <li>Abrí el día donde está el cheque.</li>
    <li>Presioná el botón de la <strong>papelera</strong> al lado del cheque.</li>
    <li>Confirmá la eliminación.</li>
</ol>

<div class="ayuda-warning">
    <strong>Importante:</strong> la eliminación es <strong>definitiva</strong>. Si te equivocaste,
    vas a tener que volver a cargarlo desde cero.
</div>

<h3>Vista del calendario</h3>
<p>El calendario tiene 3 vistas que podés cambiar desde los botones de arriba a la derecha:</p>
<ul>
    <li><strong>Mes</strong> — grilla clásica mensual, ideal para ver el panorama completo.</li>
    <li><strong>Semana</strong> — vista semanal, útil para organizar los cheques de la semana.</li>
    <li><strong>Agenda</strong> — lista cronológica de los cheques, agrupados por día.</li>
</ul>
<p>
    Con las flechas <strong>&lt;</strong> y <strong>&gt;</strong> navegás al mes o semana anterior/siguiente.
    El botón <strong>Hoy</strong> te lleva al día actual.
</p>

<h3>Cómo se muestran los cheques en el calendario</h3>
<ul>
    <li>Si en un día hay <strong>un solo cheque</strong>, el evento muestra el monto y el banco
        (o parte de la descripción) en color rojo.</li>
    <li>Si hay <strong>varios cheques</strong>, el evento muestra la cantidad y el total del día
        en color verde.</li>
    <li>Al hacer clic en el evento, se abre el mismo modal con todos los cheques de ese día.</li>
</ul>

<h3>Permisos</h3>
<ul>
    <li><strong>Admin / Dev:</strong> acceso total (agregar, editar, eliminar).</li>
    <li><strong>Vendedor:</strong> puede agregar, editar y eliminar cheques.</li>
    <li><strong>Productor:</strong> solo puede ver el calendario, sin modificar nada.</li>
</ul>

<div class="ayuda-tip">
    <strong>Relacionado:</strong> los cheques que vencen <strong>mañana</strong> aparecen
    automáticamente destacados en el <strong>Dashboard</strong>, así no se te pasan por alto.
</div>